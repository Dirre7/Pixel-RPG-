export function areZoneMainQuestsCompleted(
  zoneId: string,
  completedQuests: string[] = []
): { isUnlocked: boolean; pendingQuests: NPCQuest[]; totalMainQuests: number } {
  const prerequisiteMainQuests = ALL_GAME_QUESTS.filter(
    (q) => q.zoneId === zoneId && q.category === 'main' && q.targetType !== 'defeat_boss'
  );
  const pendingQuests = prerequisiteMainQuests.filter((q) => !completedQuests.includes(q.id));
  return {
    isUnlocked: pendingQuests.length === 0,
    pendingQuests,
    totalMainQuests: prerequisiteMainQuests.length,
  };
}
